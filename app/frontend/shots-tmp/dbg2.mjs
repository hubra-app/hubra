import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const p = await (await b.newContext()).newPage()
p.on('pageerror', e => console.log('pageerror', e.message.slice(0,200)))
p.on('response', r => { if (r.url().includes('/api/')) console.log(r.status(), r.url()) })
await p.goto('http://localhost:5175/login?redirect=' + encodeURIComponent('http://localhost:5173/demo/app/dashboard'))
await p.getByLabel(/E-Mail/i).first().fill('admin@demo.test')
await p.getByLabel(/Passwort|Password/i).first().fill('Demo-Passwort-2026!')
await p.keyboard.press('Enter'); await p.waitForTimeout(8000)
console.log(p.url()); console.log((await p.textContent('body')).slice(0,300)); await b.close()
